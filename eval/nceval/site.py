#: The newer formats: the README compares the references' speed with these Defaults.
NEWER_FORMATS = ("hevc", "vvc", "av1", "vp9", "av2")
#: A preset within this many points of the zero line (or behind it) is "not ahead".
NOT_AHEAD_POINTS = 1.0
CODECS_PAGE = "https://cribbinsb.github.io/nanocodec/results/codecs.html"
COUNT_WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
               8: "eight", 9: "nine", 10: "ten"}


def fps_range(values: list[float]) -> str:
    return f"{min(values):.0f}–{max(values):.0f}"


def names(labels: list[str]) -> str:
    """"a", "a and b", "a, b and c"."""
    return labels[0] if len(labels) == 1 else f"{', '.join(labels[:-1])} and {labels[-1]}"


def readme_block(chart: dict) -> str:
    """The README's headline facts, one line each, against the PSNR-tuned x264
    medium on the held-out clips (fresh, and all held-out beside it)."""
    views = {v["id"]: v for v in chart["views"]}
    fresh_view, held_view = views["fresh-psnr"], views["heldout-psnr"]
    fresh, held = fresh_view["values"], held_view["values"]
    pts = chart["points"]
    defaults = [f for f, p in pts.items() if p["ours"] and p["preset"] == DEFAULT_PRESET
                and f in fresh]
    newer = [f for f in defaults if pts[f]["codec"] in NEWER_FORMATS]
    not_ahead = [f for f, p in pts.items() if p["ours"] and f in fresh
                 # a family only the fresh chart has yet (a new rung) is judged on it alone
                 and max(fresh[f]["j"], held.get(f, fresh[f])["j"]) > -NOT_AHEAD_POINTS]
    slowest_newer = max(fresh[f]["fps"]["jetson"] for f in newer)
    faster_refs = sorted((f for f, p in pts.items() if not p["ours"] and not p["tune"]
                          and f in fresh and fresh[f]["fps"]["jetson"] > slowest_newer),
                         key=lambda f: -fresh[f]["fps"]["jetson"])
    zero = fresh[TUNED_ZERO]

    def pct(values: list[float]) -> str:
        return f"{-max(values):.1f}–{-min(values):.1f}%"

    def short(f: str) -> str:
        return pts[f]["label"].removeprefix("nanocodec ")

    behind = []
    if not_ahead:
        behind.append(f"{names([short(f) for f in not_ahead])} (little or no saving)")
    if faster_refs:
        count = COUNT_WORDS.get(len(faster_refs), str(len(faster_refs)))
        behind.append(f"the speed of {count} reference settings against our newer formats")
    facts = [
        f"- **Bits:** in real-time, low-delay CBR (same targets, 1 s buffer, no B-frames or "
        f"lookahead, one thread), our default (`medium`) presets need {pct([fresh[d]['j'] for d in defaults])} "
        f"fewer bits for the same quality than x264 {fresh_view['tools']['x264']} "
        f"`medium --tune zerolatency,psnr` on {fresh_view['clips']} fresh held-out clips "
        f"({pct([held[d]['j'] for d in defaults])} on all {held_view['clips']}).",
        f"- **Speed:** {fps_range([fresh[d]['fps']['jetson'] for d in defaults])} fps at 720p on "
        f"one Jetson Orin Nano core, {fps_range([fresh[d]['fps']['x86'] for d in defaults])} on "
        f"one AMD EPYC 9R45 (Zen 5) core (that x264: {zero['fps']['jetson']:.0f} and "
        f"{zero['fps']['x86']:.0f}).",
        f"- **Where we are behind:** {' and '.join(behind)} ([details]({CODECS_PAGE})).",
    ]
    return "\n".join([README_BEGIN, *facts, README_END])


def with_readme_block(text: str, block: str) -> str:
    pattern = re.compile(re.escape(README_BEGIN) + r".*?" + re.escape(README_END), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"README.md has no {README_BEGIN!r} ... {README_END!r} block")
    return pattern.sub(lambda _: block, text)


