def best_ms(runs: list[dict], ours: bool, key: str) -> float:
    """Best round in ms per frame: ours report it, ffmpeg.wasm reports its whole run
    (start-up included) and the frame count."""
    return min(r[key] if ours else r["ms"] / r["frames"] for r in runs)


def wasm_stream_label(name: str, codec: str) -> str:
    stem = name
    for suffix in STREAM_SUFFIXES:
        stem = stem.removesuffix(suffix)
    return WASM_DECODE_STREAMS[stem.removesuffix(f".{codec}")]


def wasm_yardstick_data(chart: dict) -> dict:
    """Our browser module against ffmpeg.wasm (one thread, no SIMD), the same
    session: encode speed with the chart's quality of the same encoder and preset,
    and decode time per stream."""
    runs = json.loads(WASM_YARDSTICK.read_text())["res"]
    quality = next(v for v in chart["views"] if v["id"] == WASM_QUALITY_VIEW)["values"]
    encode, decode = [], []
    for key, rounds in runs.items():
        parts = key.split("|")
        if parts[0] == "enc":
            _, name, who = parts
            family = WASM_ENCODE_FAMILIES[name]
            ms = best_ms(rounds, who == OURS_WASM, "ms_per_frame")
            encode.append({"name": name, "family": family, "label": chart["points"][family]["label"],
                           "module": who, "ms": round(ms, 2), "fps": round(1000 / ms, 1),
                           "j": quality[family]["j"]})
    by_stream: dict[tuple[str, str], dict[str, float]] = {}
    for key, rounds in runs.items():
        parts = key.split("|")
        if parts[0] == "dec":
            _, codec, name, who = parts
            ms = best_ms(rounds, who == OURS_WASM, "decode_ms_per_frame")
            by_stream.setdefault((codec, wasm_stream_label(name, codec)), {})[who] = ms
    for (codec, label), ms in sorted(by_stream.items(),
                                     key=lambda kv: (CODEC_ORDER.index(kv[0][0]), kv[0][1])):
        ours, theirs = ms.get(OURS_WASM), ms.get(FFMPEG_WASM)
        decode.append({"codec": codec, "stream": label, "ours_ms": round(ours, 2),
                       "ref_ms": round(theirs, 2), "ratio": round(ours / theirs, 2)})
    encode.sort(key=lambda r: -r["fps"])
    return {"source": [f"docs/results/{WASM_YARDSTICK.relative_to(RESULTS)}"],
            "build": WASM_YARDSTICK_BUILD, "quality_view": WASM_QUALITY_VIEW,
            "encode": encode, "decode": decode}


