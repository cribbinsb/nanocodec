def read_csv(path: Path) -> list[dict[str, str]]:
    """A results CSV, dated ones' pre-rename family names and labels in today's form."""
    with path.open(newline="") as f:
        rows = list(csv.DictReader(f))
    for row in rows:
        if "family" in row:
            row["family"] = current_family_name(row["family"])
        if "label" in row:
            for old, new in OLD_LABEL_WORDS.items():
                row["label"] = row["label"].replace(old, new)
    return rows


def number(text: str | None) -> float | None:
    """A CSV cell as a number; empty or missing cells are None."""
    if text is None or text.strip() == "":
        return None
    return float(text.replace("+", ""))


# --- families: who, which codec, which preset, the command line ---------------------------

def anchor_kind(base: str) -> str:
    if base == OPENH264_FAMILY:
        return "openh264"
    if base.startswith("nvenc-"):
        return "nvenc"
    for kind, prefix in ANCHOR_PRESET_PREFIXES.items():
        if base.startswith(prefix) and len(base) > len(prefix):
            return kind
    raise ValueError(f"unknown family {base!r}")


def describe(family: str, label: str) -> dict:
    """Owner, codec, preset and tuning of a chart family."""
    base, _, tune = family.partition(TUNE_SEPARATOR)
    if base.startswith(OWN_PREFIX):
        codec, _, preset = base.removeprefix(OWN_PREFIX).partition("@")
        name = preset.capitalize() if preset else DEFAULT_PRESET
        return {"owner": "nanocodec", "codec": codec, "preset": name, "tune": "", "ours": True,
                "version_key": "",
                "label": f"nanocodec {label}" if preset else f"nanocodec {label} {DEFAULT_LABEL}"}
    kind = anchor_kind(base)
    project, codec, version_key = PROJECTS[kind]
    preset = base.removeprefix(ANCHOR_PRESET_PREFIXES.get(kind, base))
    return {"owner": project, "codec": codec, "preset": preset, "tune": tune, "ours": False,
            "version_key": version_key, "label": label}


def program_tool(kind: str, _paths) -> Path:
    """An anchor's program by name only: the site shows commands, it runs nothing."""
    return Path(ANCHOR_TOOLS[kind])


def chart_family(family: str) -> Family:
    """The harness's Family for a chart point, with tool paths as program names."""
    base, _, _ = family.partition(TUNE_SEPARATOR)
    if base.startswith(OWN_PREFIX):
        codec, _, preset = base.removeprefix(OWN_PREFIX).partition("@")
        return Family(base, Codec(codec), Path(OWN_TOOL), preset_cli_args(codec, preset),
                      own=True)
    if base == OPENH264_FAMILY:
        return Family(family, Codec.H264, Path(OPENH264_TOOL), kind="openh264",
                      profile=family.partition(TUNE_SEPARATOR)[2])
    return preset_anchor(family, load_paths(), tool=program_tool)


def cbr_command(family: str) -> str | None:
    """The CBR command line of a chart point at the example clip and rate."""
    if family.startswith("nvenc-"):
        return None  # ffmpeg with a GPU encoder: described in the method, not a CPU command
    argv = chart_family(family).command(EXAMPLE_CLIP, DEFAULT_FRAMES, EXAMPLE_INTRA_PERIOD,
                                        EXAMPLE_OUTPUT, None, kbps=EXAMPLE_KBPS)
    return " ".join(argv)


def timing_commands(plan: dict) -> dict[str, dict]:
    """The fixed-QP timing command of each family on the plan's first clip."""
    out = {}
    for family, clips in plan["points"].items():
        clip = sorted(clips)[0]
        argv = [Path(a.replace("{BIN}/", "")).name if a.startswith("{BIN}") else a
                for a in clips[clip]["argv"]]
        argv = [{"{INPUT}": "input.yuv", "{OUTPUT}": str(EXAMPLE_OUTPUT)}.get(a, a) for a in argv]
        out[family] = {"clip": clip, "qp": clips[clip]["qp"], "command": " ".join(argv)}
    return out


