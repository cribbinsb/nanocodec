def wasm_data() -> dict:
    """Browser-build speed per codec, direction, preset and size: frame-weighted over
    the clips (decode: decode alone; encode: the demo's whole encode call), with the
    native build's fps on the same streams."""
    rows = [r for r in read_csv(RESULTS / WASM_CSV)
            if r["module"] == WASM_MODULE and r["control"] == "0"]
    groups: dict[tuple, list[dict]] = {}
    for r in rows:
        groups.setdefault((r["direction"], r["codec"], r["preset"], r["res"]), []).append(r)
    out = []
    for (direction, codec, preset, res), group in sorted(groups.items()):
        frames = sum(int(r["frames"]) for r in group)
        if direction == "decode":
            wasm_ms = sum(int(r["frames"]) * float(r["wasm_decode_ms"]) for r in group)
        else:
            wasm_ms = sum(int(r["frames"]) * 1000 / float(r["wasm_fps"]) for r in group)
        native_ms = sum(int(r["frames"]) * 1000 / float(r["native_fps"]) for r in group)
        builds = sorted({r["build"] for r in group})
        out.append({"direction": direction, "codec": codec, "preset": preset or None,
                    "res": res, "clips": len(group), "builds": builds,
                    "wasm_fps": round(frames * 1000 / wasm_ms, 1),
                    "native_fps": round(frames * 1000 / native_ms, 1),
                    "seed_caveat": direction == "encode" and codec in WASM_SEED_CAVEAT_CODECS
                    and WASM_SEED_CAVEAT_BUILD in builds})
    return {"source": [f"docs/results/{WASM_CSV}"], "module": WASM_MODULE, "rows": out}


def window_data() -> dict:
    """BD per metric with 95% intervals over 150 and 600 frames on the same sources,
    against x264 medium at both tunings, and the 600-frame rate record."""
    metrics = ("j", "psnr_yuv", "vmaf_v1", "ms_ssim")

    def block(row: dict[str, str]) -> dict:
        return {m: [number(row[f"{m}_pct"]), number(row[f"{m}_lo"]), number(row[f"{m}_hi"])]
                for m in metrics}

    out: dict = {"source": [], "families": {}}
    for span, stem in WINDOW_FILES.items():
        for zero, suffix in ((DEFAULT_ZERO, "bd"), (TUNED_ZERO, "alt_anchor")):
            path = INDEPENDENT / f"{stem}-{suffix}.csv"
            out["source"].append(f"docs/results/{path.relative_to(RESULTS)}")
            for r in read_csv(path):
                if suffix == "bd" and r["group"] != WINDOW_GROUP:
                    continue
                if suffix == "alt_anchor" and r["anchor"] != TUNED_ZERO:
                    continue
                entry = out["families"].setdefault(r["family"], {})
                entry.setdefault(span, {})[zero] = block(r)
                if suffix == "bd":
                    out.setdefault("clips", int(r["clips"]))
    rate = INDEPENDENT / f"{WINDOW_FILES['long']}-rate.csv"
    out["source"].append(f"docs/results/{rate.relative_to(RESULTS)}")
    for r in read_csv(rate):
        entry = out["families"].setdefault(r["family"], {})
        entry["rate_long"] = {"ratio_median": number(r["ratio_median"]),
                              "points": int(r["points"]),
                              "points_over_buffer": int(r["points_over_buffer"])}
    labels = {f: describe(f, f)["owner"] for f in out["families"]}
    out["owners"] = labels
    return out


