"""What under ~/nanocodec-data is kept, and the one gate every deletion goes through.

Owner, 2026-11-21: "CLEARLY differentiate between files that are important to keep and
those that are not". That day a clean-up judged `work/realuse` by age and deleted the
main chart's point store (1,554 points) and the history page's points with it, while
~30 GB that nothing reads stayed. The distinction is now made in two places:

  - the manifest, tools/dev/retention.toml: every kept path or pattern under the data
    root with its class, the tool that reads it, what regenerating it costs and, for
    caches, a size cap; and the paths declared `regenerable` (free to delete);
  - at the files: a MARKER file (`NANOCODEC-KEEP.md`) in each kept directory, written by
    `retention.py mark` and by the tools that create durable stores (`ensure_marker`).

    check(path)       strict: True only for a path that is declared regenerable, or an
                      agent's own scratch (scratch/<agent>/) or build target (targets/);
                      a kept, marked or UNKNOWN (undeclared) path is refused. Every
                      deletion by an agent or the coordinator goes through it.
    guard(path, owner)  for a tool evicting its own outputs by exact identity (a cache's
                      eviction, a chart's replaced points): only kept and marked paths
                      are refused; an owner named in `evicted_by` may remove inside.
    status / sweep    what is sweepable (declared, past grace, unused) and what is UNKNOWN.
    verify_release    the release's durable stores: present and not empty.

"Old", "big", "agent finished" and "not modified recently" are never reasons to delete.
"""

from __future__ import annotations

import datetime
import fnmatch
import functools
import os
import shutil
import subprocess
import time
import tomllib
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
MANIFEST_ENV = "NC_RETENTION_MANIFEST"
DATA_ROOT_ENV = "NC_DATA_ROOT"
DEFAULT_MANIFEST = REPO_ROOT / "tools" / "dev" / "retention.toml"
KEEP_CLASSES = ("durable", "tool", "cache")
#: Declared free to delete (regenerated by its tool when needed, or dead).
REGENERABLE = "regenerable"
CLASSES = KEEP_CLASSES + (REGENERABLE,)
#: Classes whose directories carry a MARKER unless the entry says `marker = false`.
MARKED_CLASSES = ("durable", "tool")
MARKER = "NANOCODEC-KEEP.md"
MARKER_HEADING = "# Keep: "
#: An agent's own scratch and build targets: deletable by their agent without a manifest
#: entry. Durable outputs are never written under SCRATCH.
SCRATCH = "scratch"
TARGETS = "targets"
#: Anything modified this recently is someone's live work (a release dry run or a
#: training run writes for hours; an agent pauses for its owner): never swept.
DEFAULT_GRACE_HOURS = 24
HOUR = 3600


@dataclass(frozen=True)
class Entry:
    path: str
    cls: str
    reader: str
    regen: str
    evicted_by: tuple[str, ...] = ()
    cap_gb: float | None = None
    release: bool = False
    require_globs: tuple[str, ...] = ()
    marker: bool = False

    @property
    def parts(self) -> tuple[str, ...]:
        return tuple(Path(self.path).parts)

    @property
    def kept(self) -> bool:
        return self.cls in KEEP_CLASSES


@dataclass(frozen=True)
class Manifest:
    entries: tuple[Entry, ...]
    grace_hours: float = DEFAULT_GRACE_HOURS


@dataclass
class Row:
    """A path `status` judged: sweepable, live (sweepable later) or UNKNOWN (refused)."""
    rel: str
    bytes: int
    age_hours: float
    state: str  # "sweepable", "live" or "unknown"
    why: str


def data_root() -> Path:
    return Path(os.environ.get(DATA_ROOT_ENV, Path.home() / "nanocodec-data"))


@functools.cache
def _load(path: Path) -> Manifest:
    raw = tomllib.loads(path.read_text())
    entries = []
    for item in raw.get("keep", []) + raw.get("regenerable", []):
        cls = item.get("class", REGENERABLE)
        if cls not in CLASSES:
            raise ValueError(f"{path}: {item['path']}: class {cls!r} not in {CLASSES}")
        entries.append(Entry(path=item["path"], cls=cls, reader=item.get("reader", ""),
                             regen=item.get("regen", ""),
                             evicted_by=tuple(item.get("evicted_by", ())),
                             cap_gb=item.get("cap_gb"), release=item.get("release", False),
                             require_globs=tuple(item.get("require_globs", ())),
                             marker=item.get("marker", cls in MARKED_CLASSES)))
    return Manifest(tuple(entries), raw.get("grace_hours", DEFAULT_GRACE_HOURS))


def manifest() -> Manifest:
    return _load(Path(os.environ.get(MANIFEST_ENV, DEFAULT_MANIFEST)))


def _relative(path: Path, root: Path) -> tuple[str, ...] | None:
    """`path`'s parts under `root`, or None when it lies outside (not ours to judge)."""
    try:
        return Path(os.path.abspath(path)).relative_to(os.path.abspath(root)).parts
    except ValueError:
        return None


def _matches(parts: tuple[str, ...], pattern: tuple[str, ...]) -> bool:
    return len(parts) == len(pattern) and all(map(fnmatch.fnmatchcase, parts, pattern))


def covering(path: Path, root: Path | None = None) -> list[tuple[Entry, str]]:
    """Each entry `path` touches, and how: "root" (it is the entry), "inside" (it lies
    within one) or "contains" (removing it would remove the entry)."""
    root = root or data_root()
    parts = _relative(path, root)
    if parts is None:
        return []
    found = []
    for entry in manifest().entries:
        pattern = entry.parts
        if not parts or (len(parts) < len(pattern) and _matches(parts, pattern[:len(parts)])):
            found.append((entry, "contains"))
        elif _matches(parts, pattern):
            found.append((entry, "root"))
        elif len(parts) > len(pattern) and _matches(parts[:len(pattern)], pattern):
            found.append((entry, "inside"))
    return found


# --- markers --------------------------------------------------------------------------


def marker_above(path: Path, root: Path | None = None,
                 except_in: frozenset[Path] = frozenset()) -> Path | None:
    """The MARKER in `path` or in a directory above it (up to the data root), other
    than those in the directories `except_in`."""
    root = Path(os.path.abspath(root or data_root()))
    path = Path(os.path.abspath(path))
    if _relative(path, root) is None:
        return None
    for directory in (path, *path.parents):
        if directory not in except_in and (directory / MARKER).is_file():
            return directory / MARKER
        if directory == root:
            break
    return None


def marker_below(path: Path) -> Path | None:
    """A MARKER anywhere under directory `path` (removing `path` would remove it)."""
    if not path.is_dir() or path.is_symlink():
        return None
    for dirpath, _, files in os.walk(path):
        if MARKER in files:
            return Path(dirpath) / MARKER
    return None


def marker_text(reader: str, regen: str, what: str, date: str | None = None) -> str:
    date = date or datetime.date.today().isoformat()
    return (f"{MARKER_HEADING}{what}\n\n"
            f"- **What reads it:** {reader}\n"
            f"- **Cost to regenerate:** {regen}\n"
            f"- **Marked:** {date}\n\n"
            "Do not delete this directory or anything in it; see tools/dev/retention.toml "
            "and docs/PROCEDURES.md \"Data retention\". Deletions go through "
            "`python3 tools/dev/retention.py check PATH`, which refuses anything at or "
            "below this file.\n")


def ensure_marker(directory: Path, reader: str, regen: str, what: str | None = None) -> Path:
    """Write `directory`'s MARKER: for a tool creating a durable store, so a regenerated
    store is marked without anyone remembering. A marker written by hand (not starting
    with MARKER_HEADING) is left as it is; one written here is refreshed."""
    directory.mkdir(parents=True, exist_ok=True)
    marker = directory / MARKER
    if not marker.exists() or marker.read_text().startswith(MARKER_HEADING):
        text = marker_text(reader, regen, what or directory.name)
        if not marker.exists() or _without_date(marker.read_text()) != _without_date(text):
            marker.write_text(text)
    return marker


def _without_date(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.startswith("- **Marked:**"))


def ensure_entry_marker(directory: Path, root: Path | None = None) -> Path | None:
    """`ensure_marker` with the text of the manifest entry `directory` is the root of
    (None when no marked entry names it)."""
    for entry, how in covering(directory, root):
        if how == "root" and entry.marker:
            return ensure_marker(directory, entry.reader, entry.regen,
                                 f"{entry.path} ({entry.cls})")
    return None


def write_markers(root: Path | None = None) -> list[tuple[Path, str]]:
    """Write the MARKER of every existing directory a marked entry names; returns
    (directory, "written" | "present")."""
    root = root or data_root()
    done = []
    for entry in manifest().entries:
        if not entry.marker:
            continue
        for directory in sorted(root.glob(entry.path)):
            if not directory.is_dir() or directory.is_symlink():
                continue
            existed = (directory / MARKER).exists()
            ensure_marker(directory, entry.reader, entry.regen, f"{entry.path} ({entry.cls})")
            done.append((directory, "present" if existed else "written"))
    return done


# --- the gates ------------------------------------------------------------------------


def guard(path: Path, owner: str | None = None, root: Path | None = None) -> str | None:
    """Why `owner` may not remove `path` (None when it may): a tool evicting its own
    outputs by exact identity calls this. A kept entry's root, a directory containing
    one, a marked path and anything holding a marker are always refused; an owner named
    in an entry's `evicted_by` may remove paths strictly inside it (that entry's own
    marker, at its root, does not stop it; a marker deeper down does)."""
    root = root or data_root()
    absolute = Path(os.path.abspath(path))
    own_roots = set()
    for entry, how in covering(path, root):
        if not entry.kept:
            continue
        if how == "inside" and owner is not None and owner in entry.evicted_by:
            depth = len(_relative(absolute, root)) - len(entry.parts)
            own_roots.add(absolute.parents[depth - 1])
            continue
        what = "contains the kept" if how == "contains" else "is kept by the manifest:"
        return (f"{path} {what} {entry.path} ({entry.cls}; read by {entry.reader}; "
                f"regenerating it: {entry.regen})")
    marker = marker_above(path, root, frozenset(own_roots)) or marker_below(path)
    if marker is not None:
        return f"{path} is marked to keep ({marker})"
    return None


def check(path: Path, root: Path | None = None) -> str | None:
    """Why `path` may not be deleted (None when it may). Strict: beyond `guard`, a path
    must be declared regenerable, or be an agent's scratch or build target; anything
    else is UNKNOWN, and UNKNOWN is kept."""
    root = root or data_root()
    refused = guard(path, root=root)
    if refused is not None:
        return refused
    parts = _relative(path, root)
    if parts is None:
        return None  # outside the data root: not this manifest's to judge
    if len(parts) >= 2 and parts[0] in (SCRATCH, TARGETS):
        return None
    if any(e.cls == REGENERABLE and how in ("root", "inside") for e, how in covering(path, root)):
        return None
    return (f"{path} is UNKNOWN: not declared regenerable in tools/dev/retention.toml "
            f"(UNKNOWN is kept; classify it first)")


# --- status and sweep -----------------------------------------------------------------


def _git_worktrees() -> set[Path]:
    out = subprocess.run(["git", "-C", str(REPO_ROOT), "worktree", "list", "--porcelain"],
                         capture_output=True, text=True).stdout
    return {Path(line.split(" ", 1)[1]) for line in out.splitlines()
            if line.startswith("worktree ")}


def _process_dirs() -> list[Path]:
    """Every process's working directory: a path one of them sits in is in use."""
    found = []
    for pid in os.listdir("/proc"):
        if pid.isdigit():
            try:
                found.append(Path(os.readlink(f"/proc/{pid}/cwd")))
            except OSError:
                pass
    return found


def _walk(path: Path) -> tuple[int, float]:
    """(bytes on disk, newest mtime) of `path` and everything under it, not
    following symlinks or crossing filesystems."""
    try:
        top = path.lstat()
    except FileNotFoundError:
        return 0, 0.0
    total, newest = top.st_blocks * 512, top.st_mtime
    if not path.is_dir() or path.is_symlink():
        return total, newest
    for dirpath, dirs, files in os.walk(path):
        kept = []
        for name in dirs + files:
            try:
                st = os.lstat(os.path.join(dirpath, name))
            except FileNotFoundError:
                continue  # removed by a concurrent process
            newest = max(newest, st.st_mtime)
            if name in files:
                total += st.st_blocks * 512
            elif st.st_dev == top.st_dev:
                kept.append(name)
        dirs[:] = kept
    return total, newest


def candidates(root: Path | None = None) -> list[Path]:
    """The paths under `root` that are not kept: every child of a directory that
    contains a kept or declared entry, which is not kept itself (directories that
    contain entries are descended; marked directories are kept whole)."""
    root = root or data_root()
    found = []
    pending = [root]
    while pending:
        directory = pending.pop()
        for child in sorted(directory.iterdir()):
            if child.name == MARKER:
                continue
            hows = {(e.kept, how) for e, how in covering(child, root)}
            if (True, "root") in hows or (True, "inside") in hows or \
                    (child.is_dir() and (child / MARKER).is_file()):
                continue
            if any(how == "contains" for _, how in hows) and child.is_dir() \
                    and not child.is_symlink():
                pending.append(child)
            else:
                found.append(child)
    return sorted(found)


def status(root: Path | None = None, now: float | None = None) -> list[Row]:
    """Each path that is not kept, with its size: sweepable, live, or UNKNOWN."""
    root = root or data_root()
    now = time.time() if now is None else now
    grace = manifest().grace_hours
    worktrees = _git_worktrees()
    cwds = _process_dirs()
    names = {p.name for p in worktrees}
    out = []
    for path in candidates(root):
        size, newest = _walk(path)
        age = (now - newest) / HOUR
        rel = str(path.relative_to(root))
        if path in worktrees:
            state, why = "live", "a git worktree: review it, then `git worktree remove`"
        elif (path / ".git").exists():
            state, why = "live", "a git checkout: review its local changes first"
        elif age < grace:
            state, why = "live", f"modified {age:.0f} h ago (grace {grace:.0f} h)"
        elif any(c == path or path in c.parents for c in cwds):
            state, why = "live", "a running process works in it"
        elif path.parent.name == TARGETS and path.name in names:
            state, why = "live", "the target directory of a live worktree"
        elif check(path, root) is not None:
            state, why = "unknown", "not declared in tools/dev/retention.toml"
        else:
            state, why = "sweepable", "declared, or an agent's own scratch or target"
        out.append(Row(rel, size, age, state, why))
    return out


def sweep(apply: bool, root: Path | None = None, now: float | None = None,
          say=print) -> int:
    """Remove the sweepable paths (or, without `apply`, list them); returns bytes."""
    root = root or data_root()
    freed = 0
    for row in status(root, now):
        if row.state != "sweepable":
            continue
        path = root / row.rel
        if check(path, root) is not None:  # the manifest or a marker changed under us
            continue
        freed += row.bytes
        if apply:
            shutil.rmtree(path) if path.is_dir() and not path.is_symlink() else path.unlink()
            say(f"removed {row.bytes / 1e9:7.2f} GB  {path}")
        else:
            say(f"would remove {row.bytes / 1e9:7.2f} GB  {path}")
    say(f"{'freed' if apply else 'sweepable'}: {freed / 1e9:.1f} GB")
    return freed


# --- release pre-flight ---------------------------------------------------------------


def entry_bytes(path: Path) -> int:
    """A file's size, or a directory's files' sizes (symlinks not followed)."""
    if path.is_symlink() or path.is_file():
        return path.lstat().st_size
    return sum(os.lstat(os.path.join(d, f)).st_size for d, _, files in os.walk(path)
               for f in files)


def last_use(path: Path) -> float:
    """When an entry was last used: its newest access or change time (a directory's own,
    which moves when an entry is added or removed in it)."""
    info = path.lstat()
    return max(info.st_atime, info.st_mtime)


def prune_to_cap(entries: list[Path], cap_bytes: int, owner: str,
                 fixed_bytes: int = 0, min_idle_s: float = 0.0) -> tuple[int, int]:
    """A capped cache's eviction, for the tool that owns it (its manifest entry's
    `evicted_by` and `cap_gb`): the least recently used of `entries` (files or
    directories) go, each through `guard(path, owner)`, until they and `fixed_bytes`
    (what the cache holds beside them) total at most `cap_bytes`. An entry used within
    `min_idle_s` is kept, judged again just before its removal (another process may be
    using it: aws_measure's seed). Returns (bytes freed, entries removed); an entry guard
    refuses is kept and skipped."""
    sized = sorted(((last_use(e), entry_bytes(e), e) for e in entries), key=lambda t: t[0])
    total = fixed_bytes + sum(size for _, size, _ in sized)
    freed = removed = 0
    for _, size, path in sized:
        if total - freed <= cap_bytes:
            break
        if guard(path, owner) is not None:
            continue
        try:
            if time.time() - last_use(path) < min_idle_s:
                continue
            shutil.rmtree(path) if path.is_dir() and not path.is_symlink() else path.unlink()
        except FileNotFoundError:  # removed by another process meanwhile
            continue
        freed += size
        removed += 1
    return freed, removed


def cap_bytes(path: Path, root: Path | None = None) -> int | None:
    """The manifest's cap for the cache entry rooted at `path` (None: no cap)."""
    for entry, how in covering(path, root):
        if how == "root" and entry.cap_gb is not None:
            return int(entry.cap_gb * (1 << 30))
    return None


def verify_release(root: Path | None = None) -> list[str]:
    """One line per missing or empty durable store a release needs (empty: all there)."""
    root = root or data_root()
    problems = []
    for entry in (e for e in manifest().entries if e.release):
        matches = list(root.glob(entry.path)) if any(c in entry.path for c in "*?[") \
            else [root / entry.path]
        present = [p for p in matches if p.exists() and (
            p.is_file() or any(c.name != MARKER for c in p.iterdir()))]
        if not present:
            problems.append(f"missing or empty: {entry.path} ({entry.reader}); "
                            f"regenerating it: {entry.regen}")
            continue
        for pattern in entry.require_globs:
            if not any(next(p.glob(pattern), None) for p in present if p.is_dir()):
                problems.append(f"{entry.path} has nothing matching {pattern} "
                                f"({entry.reader}); regenerating it: {entry.regen}")
    return problems
