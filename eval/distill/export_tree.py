"""Write distill.deployable trees as the encoder's table, crates/nc-encoder/src/flip_trees.rs.

    python3 -m distill.export_tree NAME=RESULT.json:MODEL [...] --out crates/nc-encoder/src/flip_trees.rs

Each NAME=RESULT.json:MODEL takes the tree of MODEL (e.g. tree_depth_8) from a deployable
result; the table lists them in the given order, so `planner.flip_tree = k` selects the
k-th. Each tree's doc comment records its training (script, commit, features, seed, rung,
held-out share of the flip oracle kept).
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

import numpy as np

HEADER = """//! Generated by `eval/distill/export_tree.py` from `eval/distill/deployable.py` results:
//! the flip guide's trees (`flip_guide.rs`), selected by `planner.flip_tree` (1-based, in
//! this order). Do not edit by hand.
#![allow(
    clippy::unreadable_literal,
    reason = "generated thresholds, written as the f32 values training compared"
)]

use crate::flip_guide::{{FlipTree, TreeNode}};

/// Every tree, in `planner.flip_tree` order.
pub(crate) const TREES: [FlipTree; {count}] = [{names}];
"""


def f32_text(value: float) -> str:
    """The shortest decimal that is this value as an f32 (what the encoder compares)."""
    text = np.format_float_positional(np.float32(value), unique=True, trim="0")
    return text if "." in text else text + ".0"


def node_text(node: dict) -> str:
    if "leaf" in node:
        return f"TreeNode::Leaf({'true' if node['leaf'] else 'false'})"
    return (f"TreeNode::Inner {{ input: {node['input']}, threshold: {f32_text(node['threshold'])}_f32, "
            f"left: {node['left']}, right: {node['right']} }}")


def tree_text(name: str, result: dict, model: str) -> str:
    m = result["models"][model]
    # A rented box runs a git archive (no history): its commit is this tree's HEAD.
    commit = result["commit"] or subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                                                text=True, cwd=Path(__file__).parent).stdout.strip()
    nodes = m["tree"]["nodes"]
    doc = (f"/// `{name}`: `{model}` for {result['rung']}, `{result['script']}` at {commit[:12]}, "
           f"seed `{result['seed']}`, features `{result['features']}`; held-out share of the flip "
           f"oracle kept {m['heldout']['kept']:.1%} (fit {m['fit']['kept']:.1%}), flip rate "
           f"{m['heldout']['flip_rate']:.1%}.")
    body = ",\n    ".join(node_text(n) for n in nodes)
    return (f"{doc}\nconst {name.upper()}: FlipTree = FlipTree {{ nodes: &{name.upper()}_NODES }};\n"
            f"#[rustfmt::skip]\nconst {name.upper()}_NODES: [TreeNode; {len(nodes)}] = [\n    {body},\n];\n")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("trees", nargs="+", help="NAME=RESULT.json:MODEL")
    p.add_argument("--out", required=True, type=Path)
    args = p.parse_args()
    parts, names = [], []
    for spec in args.trees:
        name, _, rest = spec.partition("=")
        path, _, model = rest.rpartition(":")
        parts.append(tree_text(name, json.loads(Path(path).read_text()), model))
        names.append(name.upper())
    args.out.write_text(HEADER.format(count=len(names), names=", ".join(names)) + "\n"
                        + "\n".join(parts))
    print(f"{len(names)} trees -> {args.out}")


if __name__ == "__main__":
    main()
