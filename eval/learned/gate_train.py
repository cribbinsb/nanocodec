"""Fit the zero-gate network's hidden layers on a gates-off dump, and write its Rust table.

Where it fits: the zero-gate network (crates/nc-analysis/src/gate_net.rs) adds
`sum_j readout_j * h_j - weight * value` to the motion search's zero-gate scale shift; the
output terms are tuned on real encodes (nceval.tune), this script fits the rest on
gate_export.py's table (the search's own input bytes; every superblock searched in full).

Targets per superblock, from g = zero-vector SAD - best 16x16 total, per pixel (what the full
search gains over the zero vector) and its share of the zero-vector SAD r = g / (zero SAD + 1):
the value ln(1 + RELATIVE_SCALE r) (exported), the indicator r > RELATIVE_FLOOR (logistic) and
ln(1 + g), on shared hidden layers (stop_train.py's
integer network, quantisation-aware). Rows are weighted so every clip counts the same.

Reported on held-out families (indicative only): the value's correlation, and the share of
the search's gain kept when the lowest-valued superblocks skip the search, against the share
of superblocks skipped, beside the order today's gates use (the zero-vector SAD alone).

usage: gate_train.py GATE.npz OUT_DIR [--seed N] [--epochs N] [--qat-epochs N] [--dataset TEXT]
"""

import argparse
import json
import os
import sys

import numpy as np
import torch

import intnet
import stop_train as common

HEADS = 3
#: The share of the zero-vector SAD the search removes is the target, not the SAD itself: the
#: absolute gain follows the zero-vector SAD the gates already read (held-out correlation 0.98
#: with an absolute target, nothing to learn), while the share says whether the SB moves or
#: only carries noise.
RELATIVE_SCALE = 10.0
RELATIVE_FLOOR = 0.2
SHARES = (0.1, 0.25, 0.5)
TEST_VECTORS = 16
VECTOR_SEED = 2026
RUST_FILE = "gate_net_weights.rs"


def targets(t):
    sads = t["sads"]
    gain = np.clip(sads[:, 0] - sads[:, 2], 0.0, None)
    share = gain / (sads[:, 0] + 1.0)
    y = np.stack([np.log1p(RELATIVE_SCALE * share), (share > RELATIVE_FLOOR).astype(np.float64),
                  np.log1p(gain)], 1)
    return y.astype(np.float32), gain


def front(order_key, gain):
    """Skipping the search on the lowest `order_key` first: gain kept at each share skipped."""
    order = np.argsort(order_key, kind="stable")
    skipped = np.arange(1, len(order) + 1) / len(order)
    lost = np.cumsum(gain[order]) / gain.sum()
    return {f"skipped_{s}": float(1.0 - np.interp(s, skipped, lost)) for s in SHARES}


def doc(net, record):
    held = record["held_out"]
    shares = " / ".join(f"{100 * s:.0f}" for s in SHARES)
    fmt = lambda f: " / ".join(f"{100 * f[f'skipped_{s}']:.1f}" for s in SHARES)
    return [
        "Weights of the zero-gate network (GENERATED by `eval/learned/gate_train.py`: do not",
        "edit; regenerate).",
        "",
        *common.wrap(f"Network {' -> '.join(map(str, net.sizes))}, clipped `ReLU` in 0..=127, int8 weights, "
                     "run by the nc-dsp network kernels (`nn_dense_clipped`, then `nn_dense_linear`); inputs "
                     "in the order of `gate_net.rs`. `OUTPUT_ONE` output units are 1.0 of the value head's "
                     f"target, ln(1 + {RELATIVE_SCALE:g} r), r the share of the zero-vector SAD the full search "
                     "removes; the indicator and gain heads were trained beside it and are not exported.", ""),
        "",
        *common.record_lines(record),
        *common.wrap(f"- Held-out families ({held['rows']} superblocks): value correlation "
                     f"{held['value_corr']:.3f}; gain kept skipping {shares} % of the superblocks: network "
                     f"{fmt(held['network'])}, the zero-vector SAD alone {fmt(held['zero_sad'])}.", ""),
        *common.bounds_lines(net),
    ]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("data")
    parser.add_argument("out")
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--epochs", type=int, default=25)
    parser.add_argument("--qat-epochs", type=int, default=4)
    parser.add_argument("--dataset", default="the gates-off dump")
    args = parser.parse_args()
    os.makedirs(args.out, exist_ok=True)
    torch.manual_seed(args.seed)
    t = dict(np.load(args.data))
    y, gain = targets(t)
    fit, test = t["side"] == "train", t["side"] == "heldout"
    x = torch.tensor(t["inputs"][fit], dtype=torch.float32)
    sizes = (x.shape[1],) + common.HIDDEN + (HEADS,)
    model = common.QuantNet(sizes, x.mean(0), x.std(0))
    yt, wt = torch.tensor(y[fit]), torch.tensor(common.clip_weights(t["clip"][fit]))
    common.train(model, x, yt, wt, args.epochs, common.LEARNING_RATE, False)
    common.train(model, x, yt, wt, args.qat_epochs, common.QAT_LEARNING_RATE, True)
    net = model.to_intnet()
    bytes_test = t["inputs"][test]
    integer = intnet.forward(net, bytes_test)
    with torch.no_grad():
        in_torch = model(torch.tensor(bytes_test, dtype=torch.float32), True)[:, 0].numpy()
    assert np.array_equal(np.rint(in_torch.astype(np.float64) * net.output_unit), integer)
    value = integer / net.output_unit
    held = {"rows": int(test.sum()), "value_corr": float(np.corrcoef(value, y[test, 0])[0, 1]),
            "network": front(value, gain[test]), "zero_sad": front(t["sads"][test, 0], gain[test]),
            "per_class": {str(c): front(value[t["class"][test] == c], gain[test][t["class"][test] == c])
                          for c in np.unique(t["class"][test]) if gain[test][t["class"][test] == c].sum() > 0}}
    record = {"argv": ["eval/learned/gate_train.py", *sys.argv[1:]], "seed": args.seed,
              "torch": torch.__version__, "data": args.data, "data_sha256": common.sha256(args.data),
              "dataset": args.dataset, "sizes": list(net.sizes), "held_out": held,
              "fit_rows": int(fit.sum())}
    rng = np.random.default_rng(VECTOR_SEED)
    vectors = np.concatenate([np.zeros((1, sizes[0]), np.uint8),
                              np.full((1, sizes[0]), intnet.ACTIVATION_MAX, np.uint8),
                              rng.integers(0, 128, (4, sizes[0]), dtype=np.uint8),
                              bytes_test[np.sort(rng.choice(len(bytes_test), TEST_VECTORS - 6, replace=False))]])
    outputs = intnet.forward(net, vectors)
    intnet.save(os.path.join(args.out, "gate_net.npz"), net)
    with open(os.path.join(args.out, RUST_FILE), "w") as f:
        f.write(common.rust_source(net, doc(net, record), vectors, outputs))
    with open(os.path.join(args.out, "gate_training.json"), "w") as f:
        json.dump(record, f, indent=1)
    print(json.dumps(held, indent=1))


if __name__ == "__main__":
    main()
