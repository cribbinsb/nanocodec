#!/usr/bin/env python3
"""Extract fixed-CDF AV2 coefficient (TX4..TX64, all planes), transform-type and transform-partition tables from pinned permissively licensed AVM.

Usage: gen_coeff_tables.py SOURCE BUILD > crates/nc-av2/src/coeff_tables.rs
Only reads original headers; the temporary compiled extractor is not shipped.
"""
import pathlib
import subprocess
import sys
import tempfile

source, build = map(pathlib.Path, sys.argv[1:])
revision = subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip()
assert revision == '966a7d7cd6fcf60360caf5dc413b2aeeb65e144d', revision
# (name, dims, expression): dims start with the four quantizer categories
# except for UNQUANTIZED; letters a, b, c, d index the dims in order.
UNQUANTIZED = ('INTER_TX', 'INTER_TX_SET', 'INTER_TX_IDX', 'INTER_TX_OFFSET1',
               'INTER_TX_OFFSET2', 'INTRA_TX', 'INTRA_TX_FULL', 'TX_SPLIT', 'TX_PARTITION')
specs = [
 ('SKIP', [4,2,5,10,2], 'av2_default_txb_skip_cdfs[a][b][c][d]'),
 ('V_SKIP', [4,12,2], 'av2_default_v_txb_skip_cdfs[a][b]'),
 ('EOB16', [4,3,5], 'av2_default_eob_multi16_cdfs[a][b]'),
 ('EOB64', [4,3,7], 'av2_default_eob_multi64_cdfs[a][b]'),
 ('EOB256', [4,3,8], 'av2_default_eob_multi256_cdfs[a][b]'),
 ('EOB1024', [4,3,8], 'av2_default_eob_multi1024_cdfs[a][b]'),
 ('EXTRA', [4,2], 'av2_default_eob_extra_cdfs[a]'),
 ('SIGN', [4,3,2], 'av2_default_dc_sign_cdfs[a][0][0][b]'),
 ('SIGN_HIDDEN', [4,3,2], 'av2_default_dc_sign_cdfs[a][0][1][b]'),
 ('BASE_PH', [4,5,4], 'av2_default_coeff_base_ph_cdfs[a][b]'),
 ('BASE_EOB', [4,5,4,3], 'av2_default_coeff_base_eob_multi_cdfs[a][b][c]'),
 ('BASE_LF_EOB', [4,5,4,5], 'av2_default_coeff_base_lf_eob_multi_cdfs[a][b][c]'),
 ('UV_BASE_EOB', [4,4,3], 'av2_default_coeff_base_eob_multi_uv_cdfs[a][b]'),
 ('UV_BASE_LF_EOB', [4,4,5], 'av2_default_coeff_base_lf_eob_multi_uv_cdfs[a][b]'),
 ('BASE', [4,5,20,4], 'av2_default_coeff_base_multi_cdfs[a][b][c][0]'),
 ('BASE_LF', [4,5,33,6], 'av2_default_coeff_base_lf_multi_cdfs[a][b][c][0]'),
 ('BASE_TCQ', [4,5,20,4], 'av2_default_coeff_base_multi_cdfs[a][b][c][1]'),
 ('BASE_LF_TCQ', [4,5,33,6], 'av2_default_coeff_base_lf_multi_cdfs[a][b][c][1]'),
 ('UV_BASE', [4,12,4], 'av2_default_coeff_base_multi_uv_cdfs[a][b]'),
 ('UV_BASE_LF', [4,12,6], 'av2_default_coeff_base_lf_multi_uv_cdfs[a][b]'),
 ('BR', [4,7,4], 'av2_default_coeff_lps_multi_cdfs[a][b]'),
 ('BR_LF', [4,14,4], 'av2_default_coeff_lps_lf_multi_cdfs[a][b]'),
 ('UV_BR', [4,4,4], 'av2_default_coeff_lps_multi_uv_cdfs[a][b]'),
 ('INTER_TX', [3,4,2], 'default_inter_ext_tx_cdf[3][a][b]'),
 ('INTER_TX_SET', [2,3,4,2], 'default_inter_tx_type_set_cdf[a][b][c]'),
 ('INTER_TX_IDX', [2,3,8], 'default_inter_tx_type_idx_cdf[a][b]'),
 ('INTER_TX_OFFSET1', [3,8], 'default_inter_tx_type_offset_1_cdf[a]'),
 ('INTER_TX_OFFSET2', [3,4], 'default_inter_tx_type_offset_2_cdf[a]'),
 ('INTRA_TX', [4,2], 'default_intra_ext_tx_cdf[2][a]'),
 ('INTRA_TX_FULL', [4,7], 'default_intra_ext_tx_cdf[1][a]'),
 ('TX_SPLIT', [2,9,2], 'default_txfm_do_partition_cdf[0][a][b]'),
 ('TX_PARTITION', [2,14,7], 'default_txfm_4way_partition_type_reduced_cdf[0][a][b]'),
]
lines=['#include <stdio.h>', '#include "av2/common/av2_common_int.h"', '#include "av2/common/entropy_inits_coeffs.h"', '#include "av2/common/entropy_inits_modes.h"','int main(void) {']
for name, dims, expression in specs:
    for idx, size in enumerate(dims[:-1]):
        v=chr(97+idx); lines.append(f'for(int {v}=0;{v}<{size};++{v}) {{')
    lines.append(f'for(int z=0;z<{dims[-1]};++z) printf("%u ", {expression}[z]);')
    lines.extend('}' for _ in dims[:-1])
lines.append('return 0;}')
with tempfile.TemporaryDirectory(prefix='nc-av2-coeff-') as temp:
    c=pathlib.Path(temp)/'tables.c'; binary=c.with_suffix('')
    c.write_text('\n'.join(lines))
    subprocess.run(['cc','-O1','-I'+str(source),'-I'+str(build),str(c),'-o',str(binary)],check=True)
    values=iter(map(int,subprocess.check_output([str(binary)],text=True).split()))
    print('// Generated by examples/gen_coeff_tables.py from pinned AVM v1.0.0.')
    print('// Copyright Alliance for Open Media; BSD-3-Clause-Clear + AOM patent terms.')
    print('// See THIRD_PARTY.md. Fixed CDFs omit adaptive count/rate fields.')
    def array(dims):
        if len(dims)==1: return '['+', '.join(str(next(values)) for _ in range(dims[0]))+']'
        return '[\n'+',\n'.join(array(dims[1:]) for _ in range(dims[0]))+'\n]'
    for name,dims,_ in specs:
        typ='u16'
        for n in reversed(dims):typ=f'[{typ}; {n}]'
        print(f'pub(super) const {name}: {typ} = {array(dims)};')
