//! Eight-lane ADST graphs following the unchanged libvpx-derived scalar oracle.
//! Generated from `vp9_txfm/adst.rs` assignments; wide expressions retain all
//! terms until the original rounding/wrapping point. No scalar code is changed.
//! BSD-3-Clause, `WebM` project; attribution in `THIRD_PARTY.md`.

#![allow(
    clippy::too_many_lines,
    clippy::many_single_char_names,
    clippy::inline_always
)]
use super::{Lanes, Products};
use crate::vp9_txfm::VP9_COSPI_64 as C;

#[inline(always)]
pub(super) fn iadst8<V: Lanes>(input: &[V; 8], output: &mut [V; 8]) {
    let mut s0: V::Wide;
    let mut s1: V::Wide;
    let mut s2: V::Wide;
    let mut s3: V::Wide;
    let mut s4: V::Wide;
    let mut s5: V::Wide;
    let mut s6: V::Wide;
    let mut s7: V::Wide;
    let mut x0 = input[7];
    let mut x1 = input[0];
    let mut x2 = input[5];
    let mut x3 = input[2];
    let mut x4 = input[3];
    let mut x5 = input[4];
    let mut x6 = input[1];
    let mut x7 = input[6];
    s0 = V::products(C[2], x0, C[30], x1);
    s1 = V::products(C[30], x0, -(C[2]), x1);
    s2 = V::products(C[10], x2, C[22], x3);
    s3 = V::products(C[22], x2, -(C[10]), x3);
    s4 = V::products(C[18], x4, C[14], x5);
    s5 = V::products(C[14], x4, -(C[18]), x5);
    s6 = V::products(C[26], x6, C[6], x7);
    s7 = V::products(C[6], x6, -(C[26]), x7);
    x0 = s0.add(s4).round14();
    x1 = s1.add(s5).round14();
    x2 = s2.add(s6).round14();
    x3 = s3.add(s7).round14();
    x4 = s0.sub(s4).round14();
    x5 = s1.sub(s5).round14();
    x6 = s2.sub(s6).round14();
    x7 = s3.sub(s7).round14();
    s0 = x0.wide(1);
    s1 = x1.wide(1);
    s2 = x2.wide(1);
    s3 = x3.wide(1);
    s4 = V::products(C[8], x4, C[24], x5);
    s5 = V::products(C[24], x4, -(C[8]), x5);
    s6 = V::products(-C[24], x6, C[8], x7);
    s7 = V::products(C[8], x6, C[24], x7);
    x0 = s0.add(s2).narrow();
    x1 = s1.add(s3).narrow();
    x2 = s0.sub(s2).narrow();
    x3 = s1.sub(s3).narrow();
    x4 = s4.add(s6).round14();
    x5 = s5.add(s7).round14();
    x6 = s4.sub(s6).round14();
    x7 = s5.sub(s7).round14();
    s2 = V::products(C[16], x2, C[16], x3);
    s3 = V::products(C[16], x2, -(C[16]), x3);
    s6 = V::products(C[16], x6, C[16], x7);
    s7 = V::products(C[16], x6, -(C[16]), x7);
    x2 = s2.round14();
    x3 = s3.round14();
    x6 = s6.round14();
    x7 = s7.round14();
    output[0] = x0;
    output[1] = V::splat(0).sub(x4);
    output[2] = x6;
    output[3] = V::splat(0).sub(x2);
    output[4] = x3;
    output[5] = V::splat(0).sub(x7);
    output[6] = x5;
    output[7] = V::splat(0).sub(x1);
}

#[inline(always)]
