//! AV2 (AVM v1.0.0) square 2-D DCTs, 4x4 to 64x64, for 8-bit video; the
//! other transform types are in [`typed`].
//!
//! Reimplemented from AVM's `av2/common/idct.c` (`inv_txfm_c`,
//! `inv_txfm_dct2_size*_c`), `av2/encoder/hybrid_fwd_txfm.c` (`fwd_txfm_c`,
//! `fwd_txfm_dct2_size*_c`), `av2/common/txb_common.c`
//! (`tx_kernel_dct2_size*`) and `av2/common/common_data.h` (`fwd_tx_shift`,
//! `inv_tx_shift`); Alliance for Open Media, BSD-3-Clause-Clear with separate
//! AOM patent terms (see `THIRD_PARTY.md`). AVM writes each 1-D DCT as a
//! matrix product unrolled per size; here one even/odd butterfly
//! ([`generic`]) serves every size, which is exact because the integer
//! matrices nest (below) and every pass rounds only its final dot products.
//!
//! # Matrices
//!
//! AV2 uses integer DCT-II matrices, neither AV1's cosine butterflies nor
//! HEVC's table (HEVC has 36 where AV2 has 35, 25 where AV2 has 26, ...). All
//! five AVM matrices are generated by [`DCT_COSINE`]: the `N`-point basis
//! vector `k` at sample `j` is `±DCT_COSINE[m]`, where `m` folds the phase
//! `(2j + 1) · k · 64 / N` (in units of `π / 128`) into the first quadrant.
//! Hence the `N`-point vector `k` is the 64-point vector `k · 64 / N`
//! truncated to `N` samples ([`DCT_BASIS`]), and the even rows of each matrix
//! are the half-size matrix. `tools/codegen/check_av2_dct.py` checks that
//! this rule reproduces all five AVM tables.
//!
//! # Passes (AVM `inv_txfm_c` / `fwd_txfm_c`)
//!
//! - **Inverse** (normative): coefficients are clamped to 16 bits on load,
//!   then rows (rounding shift [`Av2TxSize::inverse_shifts`]`.0`, clamp to 16
//!   bits), then columns (shift `.1`, clamp to the 8-bit residual range
//!   `-256..=255`). A 64x64 transform codes only its top-left 32x32
//!   coefficients; AVM inverts them with the *32-point* DCT and repeats every
//!   residual sample in a 2x2 square.
//! - **Forward** (encoder choice, AVM's): columns (shift `.0`), then rows
//!   (shift `.1`), no clamping. The 64x64 forward is a true 64-point DCT whose
//!   high-frequency half is never computed, so it returns 32x32 coefficients.
//!
//! Coefficients are row-major at the coded side: `coeffs[v * coded + u]`,
//! vertical frequency `v`, horizontal frequency `u`.
//!
//! # Ranges
//!
//! Every kernel computes in 32-bit lanes; nothing overflows within these
//! contracts, which match AVM's (where its C `int` arithmetic is exact):
//! - forward: residuals of 8-bit samples, `|r| <= 255`. The worst case is the
//!   64x64 row pass: `255 · 5760 >> 3` per column output, times `5760` (the
//!   largest absolute row sum of the 64-point matrix) `< 1.06 · 2^30`;
//! - inverse: inputs clamped to 16 bits, times at most `32 · 90` per output
//!   (`< 2^27`).

