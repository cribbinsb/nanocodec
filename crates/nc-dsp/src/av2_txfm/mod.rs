/// A square AV2 transform size.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Av2TxSize {
    /// `TX_4X4`.
    Tx4 = 0,
    /// `TX_8X8`.
    Tx8 = 1,
    /// `TX_16X16`.
    Tx16 = 2,
    /// `TX_32X32`.
    Tx32 = 3,
    /// `TX_64X64` (32x32 coded coefficients).
    Tx64 = 4,
}

/// Number of [`Av2TxSize`] values.
pub(crate) const AV2_TX_SIZES: usize = 5;

/// Largest side whose coefficients are all coded (AVM: `MAX_TX_SIZE >> 1`).
const MAX_CODED_SIDE: usize = 32;

/// `fwd_tx_shift` of AVM `common_data.h`, by [`Av2TxSize`].
const FORWARD_SHIFTS: [(u32, u32); AV2_TX_SIZES] = [(1, 10), (2, 10), (2, 11), (3, 12), (3, 14)];

/// `inv_tx_shift` of AVM `common_data.h`, by [`Av2TxSize`].
const INVERSE_SHIFTS: [(u32, u32); AV2_TX_SIZES] = [(7, 10), (7, 11), (6, 13), (6, 13), (6, 13)];

impl Av2TxSize {
    /// Every size, smallest first.
    pub const ALL: [Av2TxSize; AV2_TX_SIZES] = [
        Av2TxSize::Tx4,
        Av2TxSize::Tx8,
        Av2TxSize::Tx16,
        Av2TxSize::Tx32,
        Av2TxSize::Tx64,
    ];

    /// The size of side `side` (4, 8, 16, 32 or 64), or `None`.
    #[must_use]
    pub const fn from_side(side: usize) -> Option<Self> {
        match side {
            4 => Some(Self::Tx4),
            8 => Some(Self::Tx8),
            16 => Some(Self::Tx16),
            32 => Some(Self::Tx32),
            64 => Some(Self::Tx64),
            _ => None,
        }
    }

    /// Side length in samples.
    #[must_use]
    pub const fn side(self) -> usize {
        4 << self as usize
    }

    /// Side of the coded coefficient block: the side, at most 32.
    #[must_use]
    pub const fn coded_side(self) -> usize {
        if self.side() < MAX_CODED_SIDE {
            self.side()
        } else {
            MAX_CODED_SIDE
        }
    }

    /// Number of coded coefficients.
    #[must_use]
    pub const fn coded_area(self) -> usize {
        self.coded_side() * self.coded_side()
    }

    /// Rounding shifts of the forward column and row passes.
    #[must_use]
    pub const fn forward_shifts(self) -> (u32, u32) {
        FORWARD_SHIFTS[self as usize]
    }

    /// Rounding shifts of the inverse row and column passes.
    #[must_use]
    pub const fn inverse_shifts(self) -> (u32, u32) {
        INVERSE_SHIFTS[self as usize]
    }
}

/// Points of the largest DCT.
const MAX_POINTS: usize = 64;

/// 16-bit clamp of the inverse input and row pass (AVM `clamp_buf`).
const INVERSE_STAGE_MIN: i32 = -32768;
const INVERSE_STAGE_MAX: i32 = 32767;
/// Range of the inverse column pass output, the 8-bit residual range.
const INVERSE_RESIDUAL_MIN: i32 = -256;
const INVERSE_RESIDUAL_MAX: i32 = 255;

/// libaom / AVM `round_shift` for `bits >= 1`, in 64 bits (`i32` input
/// times the DC weight cannot overflow).
const fn round_shift(value: i64, bits: u32) -> i64 {
    (value + (1 << (bits - 1))) >> bits
}

/// Lane tiles of the inverse kernels: they read the coefficients by
/// tiles of at most this side (AVX2 `I32x8`).
const INVERSE_TILE: usize = 8;

impl Av2TxSize {
    /// Side of the top-left square of coefficients an inverse DCT with a
    /// `nonzero` corner reads: the corner rounded up to whole lane tiles,
    /// at most the coded side. Coefficients outside it are ignored, so a
    /// caller need only write that square.
    #[must_use]
    pub const fn inverse_read_side(self, nonzero: usize) -> usize {
        let side = nonzero.next_multiple_of(INVERSE_TILE);
        if side < self.coded_side() {
            side
        } else {
            self.coded_side()
        }
    }

    /// The residual of an inverse DCT whose only nonzero coefficient is the
    /// DC `dc`: one value for every sample. The DC basis vector is the
    /// constant [`DC_WEIGHT`] at every size, so the row pass turns row 0
    /// into one clamped value and the column pass every column into one
    /// clamped sample; the 64x64 repetition of the 32x32 result keeps it
    /// constant. The same clamps and shifts as the full inverse, so the
    /// result equals every sample of it (exact).
    #[must_use]
    pub const fn inverse_dc_residual(self, dc: i32) -> i32 {
        let (first, second) = self.inverse_shifts();
        let dc = clamp(dc, INVERSE_STAGE_MIN, INVERSE_STAGE_MAX) as i64;
        let row = round_shift(dc * DC_WEIGHT as i64, first);
        let row = clamp_i64(row, INVERSE_STAGE_MIN, INVERSE_STAGE_MAX);
        let sample = round_shift(row * DC_WEIGHT as i64, second);
        clamp_i64(sample, INVERSE_RESIDUAL_MIN, INVERSE_RESIDUAL_MAX) as i32
    }
}

const fn clamp(value: i32, low: i32, high: i32) -> i32 {
    if value < low {
        low
    } else if value > high {
        high
    } else {
        value
    }
}

const fn clamp_i64(value: i64, low: i32, high: i32) -> i64 {
    if value < low as i64 {
        low as i64
    } else if value > high as i64 {
        high as i64
    } else {
        value
    }
}

/// Weight of the DC basis vector (`tx_kernel_dct2_size*[.][0][.]`).
const DC_WEIGHT: i32 = 64;

/// AVM's integer cosines: entry `m` (1..=63) is `64·√2·cos(m·π/128)`
/// rounded to nearest, except `m = 16` (83, not 84); entry 0 is the DC
/// weight.
#[rustfmt::skip]
const DCT_COSINE: [i8; MAX_POINTS] = [
    64, 90, 90, 90, 90, 90, 90, 89, 89, 88, 88, 87, 87, 86, 85, 84,
    83, 83, 82, 81, 80, 79, 78, 76, 75, 74, 73, 71, 70, 69, 67, 66,
    64, 62, 61, 59, 57, 56, 54, 52, 50, 48, 47, 45, 43, 41, 39, 37,
    35, 33, 30, 28, 26, 24, 22, 20, 18, 15, 13, 11, 9, 7, 4, 2,
];

/// Entry `(k, j)` of the 64-point matrix: cosine of phase `(2j + 1) · k`
/// (in `π / 128`), folded by `cos(2π − a) = cos(a)` and
/// `cos(π − a) = −cos(a)`.
const fn basis_entry(k: usize, j: usize) -> i8 {
    let phase = (2 * j + 1) * k % (4 * MAX_POINTS);
    let unsigned = if phase > 2 * MAX_POINTS {
        4 * MAX_POINTS - phase
    } else {
        phase
    };
    if unsigned > MAX_POINTS {
        -DCT_COSINE[2 * MAX_POINTS - unsigned]
    } else {
        DCT_COSINE[unsigned]
    }
}

/// The first half of every 64-point basis vector: `DCT_BASIS[k][j]` for
/// `j < 32`. The second half mirrors it (`(−1)^k` times sample `63 − j`),
/// which the butterflies exploit; the `N`-point vector `k` is row `k · 64 / N`.
pub(crate) const DCT_BASIS: [[i8; MAX_POINTS / 2]; MAX_POINTS] = {
    let mut rows = [[0; MAX_POINTS / 2]; MAX_POINTS];
    let mut k = 0;
    while k < MAX_POINTS {
        let mut j = 0;
        while j < MAX_POINTS / 2 {
            rows[k][j] = basis_entry(k, j);
            j += 1;
        }
        k += 1;
    }
    rows
};

