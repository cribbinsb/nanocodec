#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bit_table_is_the_logarithm() {
        for (i, &bits) in BITS.iter().enumerate() {
            let p = (i as f32 + 0.5) / PROBABILITY_STATES as f32;
            assert!((bits + p.log2()).abs() <= f32::EPSILON * bits, "state {i}");
        }
    }
}
