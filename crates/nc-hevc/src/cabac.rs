#[cfg(test)]
mod tests {
    use super::*;
    use nc_common::cabac::CabacReader;

    #[test]
    fn bit_table_is_the_model() {
        const P_LPS_0: f32 = 0.5;
        const P_LPS_62: f32 = 0.01875;
        for (state, &[lps, mps]) in BITS.iter().enumerate() {
            let p_lps = P_LPS_0 * (P_LPS_62 / P_LPS_0).powf(state as f32 / 63.0);
            for (bits, p) in [(lps, p_lps), (mps, 1.0 - p_lps)] {
                assert!(
                    (bits + p.log2()).abs() <= f32::EPSILON * bits,
                    "state {state}"
                );
            }
        }
    }

    #[test]
    fn context_init_matches_the_specification() {
        // initValue 154 is "equiprobable": pStateIdx 0 or 1 near QP 26.
        let c = Context::new(154, 26);
        assert!(c.state() <= 1);
        // initValue 139 at QP 30: slope -5, offset 72, preCtxState
        // ((-5 * 30) >> 4) + 72 = 62 < 64, so valMps 0 and pStateIdx 1.
        assert_eq!(Context::new(139, 30), Context(1 << 1));
    }

    #[test]
    fn decisions_bypass_and_terminate_round_trip() {
        // A deterministic pseudo-random mix of all three bin kinds.
        let mut seed = 0x2545_f491_4f6c_dd1du64;
        let mut next = || {
            seed ^= seed << 13;
            seed ^= seed >> 7;
            seed ^= seed << 17;
            seed
        };
        let inits = [139u8, 154, 63, 184, 111];
        let mut enc_ctx: Vec<Context> = inits.iter().map(|&i| Context::new(i, 32)).collect();
        let mut ops = Vec::new();
        let mut enc = CabacWriter::new();
        for _ in 0..5000 {
            let r = next();
            match r % 4 {
                0 | 1 => {
                    let c = (r >> 8) as usize % inits.len();
                    // Skewed bins so states move away from equiprobable.
                    let bin = (r >> 16) % 5 == 0;
                    enc.encode_bin(&mut enc_ctx[c], bin);
                    ops.push((0, c as u32, u32::from(bin)));
                }
                2 => {
                    let n = 1 + ((r >> 8) % 16) as u32;
                    let v = (r >> 24) as u32 & ((1 << n) - 1);
                    enc.encode_bypass(v, n);
                    ops.push((1, n, v));
                }
                _ => {
                    enc.encode_terminate(false);
                    ops.push((2, 0, 0));
                }
            }
        }
        enc.encode_terminate(true);
        let mut bits = enc.finish();
        bits.trailing_bits();
        let bytes = bits.into_bytes();

        let mut dec_ctx: Vec<Context> = inits.iter().map(|&i| Context::new(i, 32)).collect();
        // The decoders' shared engine reads it back.
        let mut dec = CabacReader::new(&bytes, 0).expect("a coded stream");
        for (kind, a, b) in ops {
            match kind {
                0 => assert_eq!(u32::from(dec.decision(&mut dec_ctx[a as usize].0)), b),
                1 => {
                    let v = (0..a).fold(0, |v, _| (v << 1) | u32::from(dec.bypass()));
                    assert_eq!(v, b);
                }
                _ => assert!(!dec.terminate()),
            }
        }
        assert!(dec.terminate());
    }
}
