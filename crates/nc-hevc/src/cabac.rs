//! The CABAC arithmetic encoder (HEVC §9.3.4.3) and its context models.
//!
//! The engine follows kvazaar's `cabac.c` (BSD-3-Clause, see
//! `THIRD_PARTY.md`), which is HM's: `low` keeps `bits_left` free bits below
//! a 32-bit window, completed bytes are held back while they are `0xff`
//! (a later carry could still change them) and released once a carry can no
//! longer reach them.

