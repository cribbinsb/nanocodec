#!/usr/bin/env bash
# Regenerate crates/nc-dsp/src/av1_inverse/dav1d_itx_neon.s, the vendored
# dav1d 1.5.4 arm64 8-bit inverse transforms (src/arm/64/itx.S), from the
# pinned dav1d source. No hand edits: the file is dav1d's assembly with its C
# preprocessor directives resolved (gcc -E), so Rust's `global_asm!` can take
# it; its gas macros stay as dav1d wrote them. dav1d's BSD-2-Clause header
# is kept at the top (THIRD_PARTY.md).
#
#   tools/dev/vendor_dav1d_itx.sh [DAV1D_SOURCE_DIR]
#
# The default source is the pinned anchor build tree. The script refuses a
# source whose itx.S, asm.S or util.S differ from dav1d 1.5.4's.
set -euo pipefail

src=${1:-$HOME/nanocodec-data/anchors/x86_64/src/dav1d-1.5.4}
root=$(cd "$(dirname "$0")/../.." && pwd)
dir=$root/crates/nc-dsp/src/av1_inverse

# dav1d 1.5.4 (tag 1.5.4, 54706fc) file hashes.
check() {
    local file=$1 want=$2
    local got
    got=$(sha256sum "$src/$file" | cut -d' ' -f1)
    [[ $got == "$want" ]] || { echo "vendor_dav1d_itx: $file is not dav1d 1.5.4's ($got)" >&2; exit 1; }
}
check src/arm/64/itx.S caca60c3574cda4f91e510ff40b43b06b5bb951cbe47e1cd9c103b1e53c87b89
check src/arm/asm.S b25a015cd950010feb49b9c94684ce002de8dfd4af0dd19a53d6fbf0734da224
check src/arm/64/util.S a505f81cd8cc3025f157cf076e1c30c5c9db43b735301dd36f29f20df7272d9b

cfg=$(mktemp -d "${TMPDIR:-/tmp}/nanocodec-vendor-dav1d-itx-XXXXXX")
trap 'rm -r -- "$cfg"' EXIT
# The configuration dav1d's meson build would write for an aarch64 ELF
# target, reduced to what asm.S reads. HAVE_AS_FUNC 0: LLVM's assembler has
# no `.func`. The prefix keeps the symbols apart from a linked libdav1d.
cat > "$cfg/config.h" <<'CONFIG'
#define ARCH_AARCH64 1
#define ARCH_ARM 0
#define HAVE_AS_FUNC 0
#define HAVE_AS_ARCH_DIRECTIVE 0
#define HAVE_AS_ARCHEXT_DOTPROD_DIRECTIVE 0
#define HAVE_AS_ARCHEXT_I8MM_DIRECTIVE 0
#define HAVE_AS_ARCHEXT_SVE_DIRECTIVE 0
#define HAVE_AS_ARCHEXT_SVE2_DIRECTIVE 0
#define PRIVATE_PREFIX nc_dav1d_
CONFIG

# One file per object format, resolved as dav1d's own build would for that target: ELF (Linux)
# and Mach-O (macOS, whose symbols carry the leading underscore: dav1d's PREFIX).
vendor() {  # vendor OUT CPP-DEFINES...
    local out=$dir/$1
    shift
    {
        sed -n '1,26p' "$src/src/arm/64/itx.S"
        cat <<'NOTE'
// GENERATED by tools/dev/vendor_dav1d_itx.sh from dav1d 1.5.4
// src/arm/64/itx.S (with src/arm/asm.S and src/arm/64/util.S): the C
// preprocessor directives resolved, nothing else changed. Do not edit.
NOTE
        gcc -E -P -x assembler-with-cpp "$@" -U__x86_64__ -I"$cfg" -I"$src" -I"$src/include" \
            -I"$src/src/arm/64" "$src/src/arm/64/itx.S"
    } > "$out"
    echo "wrote $out ($(wc -l < "$out") lines)"
}
vendor dav1d_itx_neon.s -D__ELF__
vendor dav1d_itx_neon_macho.s -U__ELF__ -U__linux__ -D__APPLE__ -D__MACH__ -DPREFIX=1
# Mach-O's one textual change: Rust assembles global_asm! into an object with
# .subsections_via_symbols, where every function symbol starts its own atom and Mach-O has no
# relocation for an ADR to another atom ("unknown AArch64 fixup kind"). dav1d's own objects lack
# that flag. Each `adr xN, <function>` becomes the ADRP + ADD pair that dav1d's movrel uses on
# Apple (the same address; one more instruction per transform call, outside the loops).
sed -i -E -e 's#^// preprocessor directives resolved, nothing else changed\. Do not edit\.$#// preprocessor directives resolved, and each ADR to a function as ADRP + ADD\n// (Mach-O, see the script); nothing else changed. Do not edit.#' \
    -e 's/^(\s*)adr (x[0-9]+), ([A-Za-z_][^ ]*_neon)$/\1adrp \2, \3@PAGE\n\1add \2, \2, \3@PAGEOFF/' \
    "$dir/dav1d_itx_neon_macho.s"
if grep -qE '^\s*adr x' "$dir/dav1d_itx_neon_macho.s"; then
    echo "vendor_dav1d_itx: an adr to a symbol is left in the Mach-O file" >&2
    exit 1
fi
