#!/usr/bin/env python3
"""Generate the AV2 guided detail filter's trained parameters
(crates/nc-dsp/src/av2_dec/gdf_tables.rs) from dav2d's src/gdf_tables.c.

    tools/codegen/gen_av2_gdf_tables.py DAV2D_SRC [--write]

DAV2D_SRC is a dav2d checkout (commit 237229e; BSD-2-Clause, see
docs/licenses/dav2d), e.g. ~/nanocodec-data/work/av2-dec/dav2d-debug. The C
file holds six intra parameter sets (one per GDF qp class) and five times
six inter sets (by reference distance class, then qp class), each with
scalar weights and an error look-up table. Without --write the generated
file is only compared with the checked-in one.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'crates/nc-dsp/src/av2_dec/gdf_tables.rs'
FIELDS = ['scale', 'bias', 'gradient_alpha', 'gradient_weight', 'alpha',
          'weight1', 'weight2', 'weight3', 'weight4', 'error_lut']


def parse_braces(text, i):
    """Parse a brace-nested list of ints starting at text[i] == '{'."""
    assert text[i] == '{'
    items, i = [], i + 1
    number = re.compile(r'-?\d+')
    while True:
        while text[i] in ' \n\t,':
            i += 1
        if text[i] == '}':
            return items, i + 1
        if text[i] == '{':
            item, i = parse_braces(text, i)
            items.append(item)
        else:
            m = number.match(text, i)
            items.append(int(m.group()))
            i = m.end()


def parse_sets(source, name):
    """The parameter sets of array `name`, as nested lists of field dicts."""
    text = re.sub(r'//[^\n]*', '', source)
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    start = text.index('{', text.index(name))
    # Each designator `.field = ` becomes a marker the parser skips; the
    # field order is checked below.
    order = re.findall(r'\.(\w+)\s*=', text[start:])
    body = re.sub(r'\.\w+\s*=', '', text[start:])
    tree, _ = parse_braces(body, 0)
    return tree, order


def to_set(fields):
    return dict(zip(FIELDS, fields))


def rust_set(s):
    def arr(values):
        return '[' + ', '.join(str(v) for v in values) + ']'

    def arr2(rows):
        return '[' + ', '.join(arr(r) for r in rows) + ']'
    lut = s['error_lut']
    lut_lines = ',\n            '.join(
        ', '.join(str(v) for v in lut[i:i + 16]) for i in range(0, len(lut), 16))
    return (f"GdfParams {{\n"
            f"        scale: {s['scale']},\n"
            f"        bias: {arr(s['bias'])},\n"
            f"        gradient_alpha: {arr(s['gradient_alpha'])},\n"
            f"        gradient_weight: {arr(s['gradient_weight'])},\n"
            f"        alpha: {arr2(s['alpha'])},\n"
            f"        weight1: {arr2(s['weight1'])},\n"
            f"        weight2: {arr2(s['weight2'])},\n"
            f"        weight3: {arr2(s['weight3'])},\n"
            f"        weight4: {arr2(s['weight4'])},\n"
            f"        error_lut: &[\n            {lut_lines},\n        ],\n"
            f"    }}")


def generate(src):
    source = (Path(src) / 'src/gdf_tables.c').read_text()
    intra, order = parse_sets(source, 'dav2d_gdf_intra_params')
    if order[:len(FIELDS)] != FIELDS:
        sys.exit(f'unexpected intra field order {order[:len(FIELDS)]}')
    inter, _ = parse_sets(source, 'dav2d_gdf_inter_params')
    intra = [to_set(s) for s in intra]
    inter = [[to_set(s) for s in row] for row in inter]
    assert len(intra) == 6 and len(inter) == 5 and all(len(r) == 6 for r in inter)
    for s in intra + [s for row in inter for s in row]:
        side = 2 * s['scale']
        assert len(s['error_lut']) == side ** 3, (s['scale'], len(s['error_lut']))
    out = ['//! The guided detail filter\'s trained parameters (dav2d `gdf_tables.c`,',
           '//! commit 237229e; Copyright © 2026 `VideoLAN` and dav2d authors,',
           '//! BSD-2-Clause, see `docs/licenses/dav2d`; from AVM v1.0.0\'s trained',
           '//! GDF models). Generated by `tools/codegen/gen_av2_gdf_tables.py',
           '//! DAV2D_SRC --write`: do not edit.',
           '',
           'use super::gdf::GdfParams;',
           '',
           '/// Intra frames\' parameters by qp class.',
           '#[rustfmt::skip]',
           'pub static INTRA: [GdfParams; 6] = [']
    out += ['    ' + rust_set(s) + ',' for s in intra]
    out += ['];', '',
            '/// Inter frames\' parameters by reference distance class, then qp',
            '/// class.',
            '#[rustfmt::skip]',
            'pub static INTER: [[GdfParams; 6]; 5] = [']
    for row in inter:
        out.append('    [')
        out += ['    ' + rust_set(s).replace('\n', '\n    ') + ',' for s in row]
        out.append('    ],')
    out += ['];', '']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('src')
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    text = generate(args.src)
    if args.write:
        OUT.write_text(text)
        print(f'wrote {OUT}')
    elif OUT.exists() and OUT.read_text() == text:
        print('PASS: generated tables match')
    else:
        sys.exit('FAIL: generated tables differ (run with --write)')


if __name__ == '__main__':
    main()
