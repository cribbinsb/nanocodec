#!/usr/bin/env python3
"""Generate the general AV2 decoder's predefined quantizer matrices from dav2d.

    tools/codegen/gen_av2_qm_tables.py DAV2D_SRC [--write]

DAV2D_SRC is a dav2d checkout at the pin below (e.g.
~/nanocodec-data/anchors/vp9-av2/src/dav2d-237229e). The script parses the two
base tables of `src/quantizer.c` (`qm_tbl_32x16`, `qm_tbl_32x32_t`), derives
every transform shape's table as `dav2d_init_predefined_qm_tables` does
(untriangle, subsample, transpose; the tables are in dav2d's transposed
coefficient order) and writes
crates/nc-av2/src/general/block/quantizer_matrices.rs. Without --write it only
checks that the checked-in file is current.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PIN = '237229ebfefd4eb8e0e25ad9636803bb93bae0c6'
OUT = ROOT / 'crates/nc-av2/src/general/block/quantizer_matrices.rs'
LEVELS = 15
PLANE_TYPES = 2
SIDES = [4, 8, 16, 32]
ROW = 20


def base_table(source, name, length):
    """The [level][plane type] lists of the C table `name`."""
    match = re.search(r'\b' + name + r'\s*\[\]\s*\[2\]\s*\[(\d+)\]\s*=\s*\{(.*?)\};', source, re.S)
    if match is None or int(match[1]) != length:
        sys.exit(f'missing table {name}[][2][{length}]')
    values = [int(v) for v in re.findall(r'\d+', match[2])]
    if len(values) != LEVELS * PLANE_TYPES * length:
        sys.exit(f'{name}: {len(values)} values, expected {LEVELS * PLANE_TYPES * length}')
    return [[values[(level * PLANE_TYPES + plane) * length:][:length] for plane in range(PLANE_TYPES)]
            for level in range(LEVELS)]


def untriangle(src, size):
    """dav2d `untriangle`: the lower triangle, row by row, to a full square."""
    dst = [0] * (size * size)
    row_start = 0
    for y in range(size):
        dst[y * size:y * size + y + 1] = src[row_start:row_start + y + 1]
        at = row_start + y
        for x in range(y + 1, size):
            at += x
            dst[y * size + x] = src[at]
        row_start += y + 1
    return dst


def subsample(src, offset, height, hstep, vstep):
    """dav2d `subsample` of a 32-wide table from `offset`."""
    return [src[offset + y * 32 + x] for y in range(0, height, vstep) for x in range(0, 32, hstep)]


def transpose(src, w, h):
    """dav2d `transpose` of a `w` x `h` table."""
    dst = [0] * (w * h)
    for y in range(h):
        for x in range(w):
            dst[x * h + y] = src[y * w + x]
    return dst


def shapes(t32x16, t32x32_triangle):
    """Every buffer of `dav2d_init_predefined_qm_tables`, by its dav2d name."""
    b = {'32x16': t32x16, '32x32': untriangle(t32x32_triangle, 32)}
    b['4x4'] = subsample(b['32x32'], 32 * 3 + 3, 32, 8, 8)
    b['8x4'] = subsample(b['32x16'], 32 * 1 + 1, 16, 4, 4)
    b['8x8'] = subsample(b['32x32'], 32 * 1 + 1, 32, 4, 4)
    b['16x4'] = subsample(b['32x16'], 32 * 1 + 0, 16, 2, 4)
    b['16x8'] = subsample(b['32x16'], 0, 16, 2, 2)
    b['16x16'] = subsample(b['32x32'], 0, 32, 2, 2)
    b['32x8'] = subsample(b['32x16'], 0, 16, 1, 2)
    b['32x4'] = subsample(b['32x16'], 32 * 1 + 0, 16, 1, 4)
    for w, h in [(8, 4), (16, 4), (16, 8), (32, 4), (32, 8), (32, 16)]:
        b[f'{h}x{w}'] = transpose(b[f'{w}x{h}'], w, h)
    return b


def set_for(buffers):
    """One level and plane type's tables, keyed by transform (w, h): dav2d
    stores coefficients transposed, so a w x h transform reads the h x w
    buffer."""
    data, offsets = [], {}
    for w in SIDES:
        for h in SIDES:
            offsets[(w, h)] = len(data)
            table = buffers[f'{h}x{w}']
            assert len(table) == w * h
            data += table
    return data, offsets


def render(dav2d):
    source = re.sub(r'/\*.*?\*/|//[^\n]*', '', (dav2d / 'src/quantizer.c').read_text(), flags=re.S)
    t32x16 = base_table(source, 'qm_tbl_32x16', 512)
    t32x32 = base_table(source, 'qm_tbl_32x32_t', 528)
    sets, offsets = [], None
    for level in range(LEVELS):
        planes = []
        for plane in range(PLANE_TYPES):
            data, offsets = set_for(shapes(t32x16[level][plane], t32x32[level][plane]))
            planes.append(data)
        sets.append(planes)
    set_len = len(sets[0][0])
    out = [
        '//! The predefined AV2 quantizer matrices (dav2d `dav2d_qm_tbl`): per',
        '//! matrix level and plane type, a weight per coefficient of every',
        '//! transform shape with sides 4..=32, in dav2d\'s transposed coefficient',
        '//! order (64-sample sides use the 32 tables).',
        '//!',
        '//! Generated by `tools/codegen/gen_av2_qm_tables.py` from dav2d',
        f'//! `src/quantizer.c` (commit {PIN[:7]}, BSD-2-Clause, see',
        '//! `docs/licenses/dav2d`); do not edit.',
        '',
        '/// Matrix levels with tables (level 15 is flat: no matrix).',
        f'pub const LEVELS: usize = {LEVELS};',
        '/// Entries of one level and plane type: every shape\'s table.',
        f'pub const SET_LEN: usize = {set_len};',
        '/// The largest side log2 (in 4-sample units) with its own tables.',
        f'pub const MAX_SIDE_LOG2: u8 = {len(SIDES) - 1};',
        '/// Where each transform shape\'s table starts in a set, by the log2 of',
        '/// its width and height in 4-sample units (0..=3).',
        f'pub const OFFSETS: [[u16; {len(SIDES)}]; {len(SIDES)}] = [',
    ]
    for w in SIDES:
        out.append('    [' + ', '.join(str(offsets[(w, h)]) for h in SIDES) + '],')
    out += ['];', '/// The tables by level, plane type (luma, chroma) and entry.', '#[rustfmt::skip]',
            f'pub static MATRICES: [[[u8; SET_LEN]; {PLANE_TYPES}]; LEVELS] = [']
    for planes in sets:
        out.append('    [')
        for data in planes:
            out.append('        [')
            for i in range(0, len(data), ROW):
                out.append('            ' + ', '.join(str(v) for v in data[i:i + ROW]) + ',')
            out.append('        ],')
        out.append('    ],')
    out.append('];')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('dav2d', type=Path)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    head = subprocess.run(['git', '-C', str(args.dav2d), 'rev-parse', 'HEAD'],
                          capture_output=True, text=True)
    if head.returncode == 0 and head.stdout.strip() != PIN:
        sys.exit(f'dav2d at {head.stdout.strip()}, expected {PIN}')
    text = render(args.dav2d)
    if args.write:
        OUT.write_text(text)
        print(f'wrote {OUT.relative_to(ROOT)}')
    elif (OUT.read_text() if OUT.exists() else '') != text:
        sys.exit(f'{OUT.relative_to(ROOT)} is stale: rerun with --write')
    else:
        print('PASS: quantizer matrices current')

if __name__ == '__main__':
    main()
