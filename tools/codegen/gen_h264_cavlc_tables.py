#!/usr/bin/env python3
"""Generate crates/nc-h264/src/tables/cavlc.rs from openh264's C++ sources.

The CAVLC residual decoder (H.264 §9.2) needs the variable-length code
tables 9-5 (coeff_token), 9-7 and 9-9a (total_zeros) and 9-10 (run_before),
and the macroblock layer the `coded_block_pattern` mapping of Table 9-4
(from openh264's decoder tables).
Their codes are extracted mechanically, as (code value, code length) pairs,
from the encoder tables of the pinned openh264 tree (BSD-2-Clause, Copyright
(c) 2013, Cisco Systems; see THIRD_PARTY.md); the decoder builds its own
lookup tables from them.

Usage:
    gen_h264_cavlc_tables.py <openh264 source dir> <output .rs file>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

SOURCE = "codec/encoder/core/src/encoder_data_tables.cpp"
CBP_SOURCE = "codec/decoder/core/src/decoder_data_tables.cpp"

# coeff_token tables of g_kuiVlcCoeffToken[nc class]: 0 <= nC < 2, 2 <= nC < 4,
# 4 <= nC < 8, (8 <= nC is a fixed-length code), nC == -1 (4:2:0 chroma DC).
COEFF_TOKEN_CLASSES = (0, 1, 2, 4)
MAX_TOTAL_COEFF = 16
MAX_TRAILING_ONES = 3


def table_body(text: str, name: str) -> str:
    """The text between the braces of `name[...] = { ... };`."""
    match = re.search(rf"{re.escape(name)}\s*(\[[^\]]*\])+\s*=\s*\{{", text)
    if not match:
        sys.exit(f"table {name} not found")
    depth, start = 1, match.end()
    for i in range(start, len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if depth == 0:
            return text[start:i]
    sys.exit(f"table {name} is not terminated")


def pairs(body: str) -> list[tuple[int, int]]:
    values = [int(v) for v in re.findall(r"-?\d+", re.sub(r"//[^\n]*", "", body))]
    return list(zip(values[::2], values[1::2]))


def rust_rows(rows: list[list[tuple[int, int]]], indent: str) -> list[str]:
    return [indent + "[" + ", ".join(f"({c}, {n})" for c, n in row) + "]," for row in rows]


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    text = (Path(sys.argv[1]) / SOURCE).read_text()
    token = pairs(table_body(text, "g_kuiVlcCoeffToken"))
    total_zeros = pairs(table_body(text, "g_kuiVlcTotalZeros"))
    chroma_dc = pairs(table_body(text, "g_kuiVlcTotalZerosChromaDc"))
    run_before = pairs(table_body(text, "g_kuiVlcRunBefore"))
    per_class = (MAX_TOTAL_COEFF + 1) * (MAX_TRAILING_ONES + 1)
    if (len(token), len(total_zeros), len(chroma_dc), len(run_before)) != (
            5 * per_class, 16 * 16, 4 * 4, 8 * 15):
        sys.exit("unexpected table sizes; has the openh264 source changed?")

    out = [
        "//! CAVLC code tables extracted from openh264's encoder tables (BSD-2-Clause,",
        "//! Copyright (c) 2013, Cisco Systems). GENERATED by",
        "//! `tools/codegen/gen_h264_cavlc_tables.py` -- do not edit by hand.",
        "//!",
        "//! Every entry is `(code value, code length)`; a length of 0 marks a",
        "//! combination that has no code.",
        "",
        "#![allow(clippy::unreadable_literal, clippy::large_const_arrays)]",
        "",
        "/// H.264 Table 9-5, `coeff_token` per nC class (0 <= nC < 2, 2 <= nC < 4,",
        "/// 4 <= nC < 8, nC == -1), indexed `[class][TotalCoeff][TrailingOnes]`.",
        "/// 8 <= nC is a 6-bit fixed-length code (§9.2.1).",
        "pub const COEFF_TOKEN: [[[(u8, u8); 4]; 17]; 4] = [",
    ]
    for cls in COEFF_TOKEN_CLASSES:
        rows = [token[cls * per_class + t * 4: cls * per_class + t * 4 + 4]
                for t in range(MAX_TOTAL_COEFF + 1)]
        out += ["    ["] + rust_rows(rows, "        ") + ["    ],"]
    out += ["];", "",
            "/// H.264 Tables 9-7 and 9-8, `total_zeros` of 4x4 blocks, indexed",
            "/// `[TotalCoeff - 1][total_zeros]`.",
            "pub const TOTAL_ZEROS: [[(u8, u8); 16]; 15] = ["]
    out += rust_rows([total_zeros[i * 16:(i + 1) * 16] for i in range(1, 16)], "    ")
    out += ["];", "",
            "/// H.264 Table 9-9a, `total_zeros` of 4:2:0 chroma DC blocks, indexed",
            "/// `[TotalCoeff - 1][total_zeros]`.",
            "pub const TOTAL_ZEROS_CHROMA_DC: [[(u8, u8); 4]; 3] = ["]
    out += rust_rows([chroma_dc[i * 4:(i + 1) * 4] for i in range(1, 4)], "    ")
    out += ["];", "",
            "/// H.264 Table 9-10, `run_before`, indexed `[min(zerosLeft, 7) - 1][run_before]`.",
            "pub const RUN_BEFORE: [[(u8, u8); 15]; 7] = ["]
    out += rust_rows([run_before[i * 15:(i + 1) * 15] for i in range(1, 8)], "    ")
    cbp_text = (Path(sys.argv[1]) / CBP_SOURCE).read_text()
    cbp = {name: [int(v) for v in re.findall(r"\d+", re.sub(r"//[^\n]*", "", table_body(cbp_text, name)))]
           for name in ("g_kuiIntra4x4CbpTable", "g_kuiInterCbpTable",
                        "g_kuiIntra4x4CbpTable400", "g_kuiInterCbpTable400")}
    out += ["];", "",
            "/// H.264 Table 9-4, `coded_block_pattern` by codeNum for 4:2:0:",
            "/// `[Intra_4x4 / Intra_8x8, Inter]`.",
            "pub const CODED_BLOCK_PATTERN_420: [[u8; 48]; 2] = [",
            "    [" + ", ".join(map(str, cbp["g_kuiIntra4x4CbpTable"])) + "],",
            "    [" + ", ".join(map(str, cbp["g_kuiInterCbpTable"])) + "],",
            "];", "",
            "/// H.264 Table 9-4, `coded_block_pattern` by codeNum for 4:0:0.",
            "pub const CODED_BLOCK_PATTERN_400: [[u8; 16]; 2] = [",
            "    [" + ", ".join(map(str, cbp["g_kuiIntra4x4CbpTable400"])) + "],",
            "    [" + ", ".join(map(str, cbp["g_kuiInterCbpTable400"])) + "],",
            "];", ""]
    Path(sys.argv[2]).write_text("\n".join(out))


if __name__ == "__main__":
    main()
