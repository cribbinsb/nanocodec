#!/usr/bin/env python3
"""Generate the AV2 decoder's warp filter tables
(crates/nc-dsp/src/av2_dec/mc_tables.rs) from dav2d's src/tables.c.

    tools/codegen/gen_av2_mc_tables.py DAV2D_SRC [--write]

DAV2D_SRC is a dav2d checkout (commit 237229e; BSD-2-Clause, see
docs/licenses/dav2d), e.g. ~/nanocodec-data/anchors/vp9-av2/src/dav2d-237229e.
It writes the extended-warp filter (63 phases of 1/64 sample, 7-bit taps)
and the affine warp filter (449 phases over [-3, 4) samples). The
interpolation filters are not generated: they are the shared AV1 taps
halved (`av2_dec::mc_8tap`). Without --write the generated file is only
compared with the checked-in one.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'crates/nc-dsp/src/av2_dec/mc_tables.rs'
TAPS = 8


def parse_rows(source, name, count):
    """The `count` 8-tap rows of the int8 array `name`."""
    text = re.sub(r'//[^\n]*', '', source)
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    start = text.index('{', text.index(name + '['))
    depth, end = 0, start
    while True:
        depth += {'{': 1, '}': -1}.get(text[end], 0)
        end += 1
        if depth == 0:
            break
    values = [int(v) for v in re.findall(r'-?\d+', text[start:end])]
    assert len(values) == count * TAPS, (name, len(values))
    return [values[i:i + TAPS] for i in range(0, len(values), TAPS)]


def rust_table(doc, name, rows):
    out = [f'/// {line}' for line in doc]
    out += ['#[rustfmt::skip]',
            f'pub(crate) static {name}: [[i8; {TAPS}]; {len(rows)}] = [']
    for i in range(0, len(rows), 4):
        out.append('    ' + ' '.join(
            '[' + ', '.join(str(v) for v in r) + '],' for r in rows[i:i + 4]))
    out += ['];', '']
    return out


def generate(src):
    source = (Path(src) / 'src/tables.c').read_text()
    ext = parse_rows(source, 'dav2d_ext_warp_filter', 63)
    warp = parse_rows(source, 'dav2d_mc_warp_filter', 7 * 64 + 1)
    for row in ext + warp:
        assert sum(row) == 128, row
    out = ['//! The AV2 warp filters (dav2d `tables.c`, commit 237229e; Copyright ©',
           '//! 2018-2026 `VideoLAN` and dav2d authors, BSD-2-Clause, see',
           '//! `docs/licenses/dav2d`). Generated by',
           '//! `tools/codegen/gen_av2_mc_tables.py DAV2D_SRC --write`: do not edit.',
           '']
    out += rust_table(
        ['`dav2d_ext_warp_filter`: the extended warp\'s 8-tap filter at phases',
         '1..=63 of 1/64 sample (index `phase - 1`; 7-bit taps).'],
        'EXT_WARP_FILTER', ext)
    out += rust_table(
        ['`dav2d_mc_warp_filter`: the affine warp\'s 8-tap filter at offsets',
         '[-3, 4) samples in 1/64 steps plus the closing entry (7-bit taps).'],
        'WARP_FILTER', warp)
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('src')
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    text = generate(args.src)
    if args.write:
        OUT.write_text(text)
        print(f'wrote {OUT}')
    elif OUT.exists() and OUT.read_text() == text:
        print('PASS: generated tables match')
    else:
        sys.exit('FAIL: generated tables differ (run with --write)')


if __name__ == '__main__':
    main()
