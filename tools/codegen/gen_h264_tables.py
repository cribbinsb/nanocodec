#!/usr/bin/env python3
"""Generate crates/nc-h264/src/tables/generated.rs from openh264's C++ sources.

H.264 CABAC needs three normative tables that are tedious and error-prone to
type by hand (H.264 §9.3.1.1 Tables 9-12 to 9-33, §9.3.3.2.1 Table 9-44 and
§9.3.3.2.1.1 Table 9-45). They are extracted mechanically from the pinned
openh264 tree (BSD-2-Clause, Copyright (c) 2013, Cisco Systems; see
THIRD_PARTY.md):

- CABAC_INIT_MN[ctxIdx][column] = (m, n), where column 0 is used for I and SI
  slices and columns 1..=3 for cabac_init_idc 0..=2;
- RANGE_TAB_LPS[pStateIdx][qCodIRangeIdx];
- TRANS_IDX[pStateIdx] = (transIdxLPS, transIdxMPS);

and the deblocking filter's Table 8-16 (alpha', beta') and Table 8-17 (tC0)
from openh264's encoder (`codec/encoder/core/src/deblocking.cpp`).

Usage:
    gen_h264_tables.py <openh264 source dir> <output .rs file>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

SOURCE = "codec/common/src/common_tables.cpp"
DEBLOCK_SOURCE = "codec/encoder/core/src/deblocking.cpp"
QP_COUNT = 52
CONTEXT_COUNT = 460


def table_body(text: str, name: str) -> str:
    """The text between the braces of `name[...] = { ... };`."""
    match = re.search(rf"{re.escape(name)}\s*(\[[^\]]*\])+\s*=\s*\{{", text)
    if not match:
        sys.exit(f"table {name} not found")
    depth, start = 1, match.end()
    for i in range(start, len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if depth == 0:
            return text[start:i]
    sys.exit(f"table {name} is not terminated")


def numbers(body: str) -> list[int]:
    body = re.sub(r"//[^\n]*", "", body).replace("CTX_NA", "0")
    return [int(v) for v in re.findall(r"-?\d+", body)]


def chunk(values: list[int], size: int) -> list[list[int]]:
    return [values[i:i + size] for i in range(0, len(values), size)]


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    text = (Path(sys.argv[1]) / SOURCE).read_text()

    init = numbers(table_body(text, "g_kiCabacGlobalContextIdx"))
    lps = numbers(table_body(text, "g_kuiCabacRangeLps"))
    trans = numbers(table_body(text, "g_kuiStateTransTable"))
    if len(init) != CONTEXT_COUNT * 4 * 2 or len(lps) != 64 * 4 or len(trans) != 64 * 2:
        sys.exit("unexpected table sizes; has the openh264 source changed?")

    out = [
        "//! CABAC tables extracted from openh264 v2.7.0 (BSD-2-Clause, Copyright (c)",
        "//! 2013, Cisco Systems). GENERATED by `tools/codegen/gen_h264_tables.py` --",
        "//! do not edit by hand.",
        "",
        "#![allow(clippy::unreadable_literal, clippy::large_const_arrays)]",
        "",
        "/// Number of CABAC context variables (H.264 ctxIdx 0..=459).",
        f"pub const CONTEXT_COUNT: usize = {CONTEXT_COUNT};",
        "",
        "/// H.264 Tables 9-12..9-33: `(m, n)` per ctxIdx; column 0 for I slices,",
        "/// columns 1..=3 for `cabac_init_idc` 0..=2. Unused entries are `(0, 0)`.",
        "pub const CABAC_INIT_MN: [[(i8, i8); 4]; CONTEXT_COUNT] = [",
    ]
    for row in chunk(chunk(init, 2), 4):
        out.append("    [" + ", ".join(f"({m}, {n})" for m, n in row) + "],")
    out += [
        "];",
        "",
        "/// H.264 Table 9-44: `rangeTabLPS[pStateIdx][qCodIRangeIdx]`.",
        "pub const RANGE_TAB_LPS: [[u8; 4]; 64] = [",
    ]
    for row in chunk(lps, 4):
        out.append("    [" + ", ".join(map(str, row)) + "],")
    out += [
        "];",
        "",
        "/// H.264 Table 9-45: `(transIdxLPS, transIdxMPS)` per pStateIdx.",
        "pub const TRANS_IDX: [(u8, u8); 64] = [",
    ]
    for lps_next, mps_next in chunk(trans, 2):
        out.append(f"    ({lps_next}, {mps_next}),")
    out += ["];", ""]

    deblock = (Path(sys.argv[1]) / DEBLOCK_SOURCE).read_text()
    alpha = numbers(table_body(deblock, "g_kuiAlphaTable"))[:QP_COUNT]
    beta = numbers(table_body(deblock, "g_kiBetaTable"))[:QP_COUNT]
    tc0 = chunk(numbers(table_body(deblock, "g_kiTc0Table")), 4)[:QP_COUNT]
    out += [
        "/// H.264 Table 8-16: `alpha'` indexed by indexA (8-bit video).",
        f"pub const DEBLOCK_ALPHA: [u8; {QP_COUNT}] = [" + ", ".join(map(str, alpha)) + "];",
        "",
        "/// H.264 Table 8-16: `beta'` indexed by indexB (8-bit video).",
        f"pub const DEBLOCK_BETA: [u8; {QP_COUNT}] = [" + ", ".join(map(str, beta)) + "];",
        "",
        "/// H.264 Table 8-17: `tC0'` indexed by indexA, for bS = 1, 2, 3.",
        f"pub const DEBLOCK_TC0: [[u8; 3]; {QP_COUNT}] = [",
    ]
    for row in tc0:
        out.append("    [" + ", ".join(map(str, row[1:])) + "],")
    out += ["];", ""]
    Path(sys.argv[2]).write_text("\n".join(out))


if __name__ == "__main__":
    main()
